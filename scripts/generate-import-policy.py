#!/usr/bin/env python3
"""Generate shell and Lean import tests from import-policy.json; --check refuses drift."""
from pathlib import Path
import sys
sys.dont_write_bytecode = True

from import_policy import POLICY, expand

ROOT = Path(__file__).resolve().parent


def generate():
    shell = ['# Generated by generate-import-policy.py. Do not edit.',
             '# Source header parsers keep their own fail-closed syntax checks.']
    lean = ['module', 'public import Lean', '', 'public section',
            'namespace AvailableChainCheckSupport.ImportPolicy', 'open Lean', '',
            '/-- Generated from scripts/import-policy.json. Do not edit. -/',
            'def accepts (rows : List (Name × Bool × Bool)) (name : Name) : Bool :=',
            '  rows.any fun (baseName, descendants, self) =>',
            '    (self && name == baseName) ||',
            '    (descendants && baseName.isPrefixOf name && name != baseName)', '']
    for library, layers in POLICY['profiles'].items():
        prefix = 'fgsa' if library == 'AvailableChainFGSA' else 'run'
        shell += [f'{prefix}_import_allowed() {{', '  case "$1:$2" in']
        lean += [f'def {prefix}AllowedImport (mod imp : Name) : Bool :=',
                 '  imp == `Init ||', '  let parts := mod.components.map (·.toString)',
                 f'  let layer := if mod == `{library} then "root"',
                 f'    else if parts.head? == some "{library}" && parts.length >= 3',
                 '    then parts[1]! else ""', '  accepts (match layer with']
        for layer, entries in layers.items():
            rows = expand(entries)
            for row in rows:
                assert not row.endswith('.**'), 'shell profiles require strict submodules'
                shell += [f'    {layer}:{row}) return 0 ;;']
            lean += [f'    | "{layer}" => [']
            for i, row in enumerate(rows):
                strict = row.endswith('.*')
                name = row[:-2] if strict else row
                comma = ',' if i < len(rows)-1 else ''
                lean += [f'      (`{name}, {str(strict).lower()}, '
                         f'{str(not strict).lower()}){comma}']
            lean[-1] += ']'
        shell += ['  esac', '  return 1', '}', '']
        lean += ['    | _ => []) imp', '']
    lean += ['end AvailableChainCheckSupport.ImportPolicy', 'end', '']
    return {'import-policy.sh': '\n'.join(shell),
            'AvailableChainCheckSupport/ImportPolicy.lean': '\n'.join(lean)}


def main():
    if sys.argv[1:] not in ([], ['--check']):
        raise SystemExit('usage: generate-import-policy.py [--check]')
    for relative, text in generate().items():
        path = ROOT / relative
        if sys.argv[1:]:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit(f'IMPORT POLICY DRIFT: {relative}')
        else:
            path.write_text(text)
    print('import policy: generated data match')


if __name__ == '__main__':
    main()
