#!/usr/bin/env bash
# Check (f), BUILD §7.3 (O19): unused imports, REPORT only.
#
# Runs `lake shake` (built into Lake v4.34.1; it reads the .olean files,
# compiles nothing and runs no lean_exe) with every library module listed
# explicitly, so the glob-only test modules are in scope (a0-s4-port.md §8,
# F5). A module with no .olean (not built by any target, e.g. SAPC.Pending)
# is skipped and listed. `--fix` is refused: the measured false positives
# (`example`-only uses, `#print axioms`, `#eval`, `open` of a namespace,
# glob-only modules) broke 15 modules under `--fix`.
#
# The report: each suggested removal as `remove <path> <import>` (the B6
# signal), and each suggested addition as `add <path> <import>`. The removals
# are compared with scripts/baselines/shake-report.txt; a removal that the
# baseline does not list is marked NEW, except a B1 downgrade (a `public import`
# removal paired with an `add` of the same plain import), which B1 forbids,
# and except a KEPT removal: its import line carries a `-- shake: keep (<reason>)`
# note (a use that shake cannot see: `#print axioms`, `example`, policy).
#
# Usage: bash scripts/shake-report.sh [--fail-on-new] [--write-baseline] [<Module>...]
#   <Module>...       check these modules only (default: every library module)
#   --fail-on-new     exit 1 if a NEW removal exists (for a gate, after keep
#                     annotations exist; not used by check-build.sh)
#   --write-baseline  write the removals to the baseline
# Exit 0: report written (findings do not fail); 1: --fail-on-new and a NEW
# removal; 2: usage error, --fix, or lake shake failed.
# B1 review decisions: .lake/clb1-import-review.md (2026-10-05).
# Keep public exports and explicit tactic/test environments; counts are live data.
# The full report: .lake/shake-report.txt (override with SHAKE_REPORT).
# SHAKE_RAW=<file>: parse this saved `lake shake` output and do not run lake
# (self-test: scripts/shake-report-selftest.sh).
set -euo pipefail
cd "$(dirname "$0")/.."
FAIL_ON_NEW=0; WRITE=0; MODS=()
for arg in "$@"; do
  case "$arg" in
    --fix|--fix=*) echo "shake-report: --fix is refused (BUILD §7.3 (f): report only)" >&2; exit 2 ;;
    --fail-on-new) FAIL_ON_NEW=1 ;;
    --write-baseline) WRITE=1 ;;
    -*) echo "shake-report: unknown option $arg" >&2; exit 2 ;;
    *) MODS+=("$arg") ;;
  esac
done
ALL=0
if [ ${#MODS[@]} -eq 0 ]; then
  ALL=1
  while IFS= read -r m; do MODS+=("$m"); done < <(python3 - <<'PY'
import os, sys
sys.path.insert(0, 'scripts'); sys.dont_write_bytecode = True
import check_common as C
for lf in C.library_files():
    olean = os.path.join('.lake/build/lib/lean', lf.module.replace('.', '/') + '.olean')
    if os.path.exists(olean):
        print(lf.module)
    else:
        print(f'shake-report: SKIPPED (no .olean; not built by any target): {lf.module}', file=sys.stderr)
PY
)
fi
REPORT=${SHAKE_REPORT:-.lake/shake-report.txt}
ERR=$(mktemp "${TMPDIR:-/tmp}/shake-err.XXXXXX"); RAW=$(mktemp "${TMPDIR:-/tmp}/shake-out.XXXXXX")
trap 'rm -f "$ERR" "$RAW"' EXIT
set +e
if [ -n "${SHAKE_RAW:-}" ]; then cp "$SHAKE_RAW" "$RAW"; RC=0
else lake shake "${MODS[@]}" > "$RAW" 2> "$ERR"; RC=$?; fi
set -e
# lake shake exits 1 when it suggests a change; an `error:` line is a failure.
if [ $RC -ne 0 ] && grep -q '^error:' "$ERR"; then
  grep -A5 '^error:' "$ERR" | head -20 >&2
  echo "shake-report: lake shake failed (rc $RC)" >&2; exit 2
fi
python3 - "$RAW" "$REPORT" "$FAIL_ON_NEW" "$WRITE" "$ALL" "${#MODS[@]}" <<'PY'
import os, re, sys
sys.path.insert(0, 'scripts'); sys.dont_write_bytecode = True
import check_common as C
raw, report, fail_on_new, write, full, nmods = sys.argv[1], sys.argv[2], sys.argv[3] == '1', sys.argv[4] == '1', sys.argv[5] == '1', sys.argv[6]
lines, path = [], None
for l in open(raw, encoding='utf-8'):
    l = l.rstrip('\n')
    m = re.match(r'^(\S.*\.lean):$', l)
    if m:
        path = os.path.relpath(m.group(1), C.ROOT)
        continue
    m = re.match(r'^\s+(remove|add) #\[(.*)\]$', l)
    if m and path:
        for imp in m.group(2).split(', '):
            lines.append(f'{m.group(1)} {path} {imp.strip()}')
    elif l.strip():
        lines.append(f'other {l.strip()}')
lines.sort()
os.makedirs(os.path.dirname(report) or '.', exist_ok=True)
with open(report, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines) + ('\n' if lines else ''))
removes = [l for l in lines if l.startswith('remove ')]
if write:
    with open(C.baseline_path('shake-report'), 'w', encoding='utf-8') as f:
        f.write('# check (f) shake-report: the removals that `lake shake` suggests on main (REPORT only; BUILD §7.3).\n')
        f.write('# Generated by: bash scripts/shake-report.sh --write-baseline\n')
        f.write('\n'.join(removes) + '\n')
    print(f'shake-report: wrote {len(removes)} baseline entries'); sys.exit(0)
base = C.read_baseline('shake-report')
# A `public import` removal paired with `add <same path> import <same module>` is a
# downgrade to a private import, which B1 forbids: it is not a NEW finding (lead-framework
# ruling 2026-09-30, fgsa-lean tool conflict).
adds = {tuple(l.split(' ', 2)[1:]) for l in lines if l.startswith('add ')}
def downgrade(l):
    _, p, imp = l.split(' ', 2)
    return imp.startswith('public import ') and (p, imp[len('public '):]) in adds
downgrades = [l for l in removes if downgrade(l)]
# `remove <path> <import>` is KEPT if a line of <path> is that import with a
# `-- shake: keep` comment (lead-framework ruling for fgsa-lean J3 STOP B).
keep_re = re.compile(r'--\s*shake:\s*keep\b')
kept_lines = {}
def kept(l):
    _, p, imp = l.split(' ', 2)
    if p not in kept_lines:
        try:
            src = open(os.path.join(C.ROOT, p), encoding='utf-8').read().splitlines()
        except OSError:
            src = []
        kept_lines[p] = {' '.join(x.split('--', 1)[0].split()) for x in src if keep_re.search(x)}
    return ' '.join(imp.split()) in kept_lines[p]
keeps = [l for l in removes if kept(l) and not downgrade(l)]
new = [l for l in removes if not base[l] and not downgrade(l) and not kept(l)]
stale = [l for l in base if l not in set(removes)] if full else []
for l in new:
    print('NEW ' + l)
files = len({l.split()[1] for l in lines if l.split()[0] in ('remove', 'add')})
print(f'shake-report: REPORT: {nmods} modules checked; {files} files with suggestions; '
      f'{len(removes)} removals ({len(new)} NEW, {len(downgrades)} B1 downgrades, {len(keeps)} kept, '
      f'{len(removes) - len(new) - len(downgrades) - len(keeps)} other in baseline), '
      f'{len(lines) - len(removes)} additions/other; {len(stale)} baseline removals no longer suggested; '
      f'full report: {report}')
sys.exit(1 if (fail_on_new and new) else 0)
PY
