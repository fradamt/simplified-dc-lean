#!/usr/bin/env python3
"""Check (b), BUILD §7.2 B2/B8 and §7.3: no `@[expose]` in a proof module
except the allow list.

A proof module is a library file that is not under Tests/ and
- is under a Proofs/ directory, or
- is a non-root module of a Kit library (AvailableChainKit,
  AvailableChainKitV2, AvailableChainKitFG), except a KitFG definition
  module listed in scripts/baselines/kitfg-def-modules.txt (step-2 ruling
  D06; the file of check (e); read if it exists), or
- is a non-root module of AvailableChainFGSAProofs.

A finding is each `expose` attribute in such a file (comments and strings
removed): `@[expose] public section`, `@[…, expose, …] <decl>`, or
`attribute [expose] <names>`. A `def`, `abbrev` or `instance` with its own
`@[expose]` is allowed when scripts/expose-allow.txt has the line
`<path> <declName>` (the E7 list: clientRow, afterFin, foldRows,
allDeliveries).

Baseline: scripts/baselines/check-expose.txt; scope:
scripts/new-libraries.txt. Exit 0: no failing finding; 1: a failing
finding."""
import argparse
import os
import re
import sys

sys.dont_write_bytecode = True
import check_common as C  # noqa: E402

NAME = 'check-expose'
KIT_LIBS = ('AvailableChainKit', 'AvailableChainKitV2', 'AvailableChainKitFG')
ALLOW = os.path.join(C.SCRIPTS, 'expose-allow.txt')
KITFG_DEF = os.path.join(C.BASELINES, 'kitfg-def-modules.txt')
ATTR = re.compile(r'(@\[|\battribute\s*\[)([^\]]*)\]')
AFTER = re.compile(r'\s*(?:(?:private|protected|public|noncomputable|partial|unsafe)\s+)*'
                   r'(section|def|abbrev|instance|theorem|lemma|structure|class|inductive|opaque)\b\s*([^\s:({\[⦃]*)')


def read_list(path, fields):
    out = set()
    if os.path.exists(path):
        for n, line in enumerate(open(path, encoding='utf-8'), 1):
            line = line.split('#', 1)[0].strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) != fields:
                sys.exit(f'{os.path.relpath(path, C.ROOT)}:{n}: expected {fields} fields: {line}')
            out.add(tuple(parts) if fields > 1 else parts[0])
    return out


def kitfg_def_modules():
    mods = set()
    for x in read_list(KITFG_DEF, 1):
        x = x[:-len('.lean')].replace('/', '.') if x.endswith('.lean') else x
        mods.add(x if x.startswith('AvailableChainKitFG') else 'AvailableChainKitFG.' + x)
    return mods


def is_proof_module(lf, kitfg_defs):
    if lf.is_test:
        return False
    if '/Proofs/' in '/' + lf.path:
        return True
    if lf.is_facade:
        return False
    if lf.lib in KIT_LIBS:
        return lf.module not in kitfg_defs
    return lf.lib in {'AvailableChainFGSAProofs', 'AvailableChainPCSAProofs'}


def main():
    a = C.standard_args(argparse.ArgumentParser(description=__doc__.split('\n')[0])).parse_args()
    scope = C.Scope()
    allow = read_list(ALLOW, 2)
    kitfg_defs = kitfg_def_modules()
    findings, n_proof = [], 0
    for lf in C.library_files():
        if not is_proof_module(lf, kitfg_defs):
            continue
        n_proof += 1
        new = scope.is_new_file(lf)
        text = lf.stripped
        for m in ATTR.finditer(text):
            items = [x.strip() for x in m.group(2).split(',')]
            if 'expose' not in items:
                continue
            line = C.line_of(text, m.start())
            if m.group(1).startswith('attribute'):
                names = text[m.end():].split('\n', 1)[0].split()
                key = f'expose-attribute {lf.path} {" ".join(names)}'
                msg = f'{lf.path}:{line}: attribute [expose] {" ".join(names)}'
            else:
                d = AFTER.match(text, m.end())
                kind, dname = (d.group(1), d.group(2)) if d else ('?', '')
                if kind == 'section':
                    key, msg = f'expose-section {lf.path}', f'{lf.path}:{line}: @[expose] section'
                else:
                    if kind in ('def', 'abbrev', 'instance') and (lf.path, dname) in allow:
                        continue
                    key = f'expose-decl {lf.path} {dname}'
                    msg = f'{lf.path}:{line}: @[expose] {kind} {dname} (not in scripts/expose-allow.txt)'
            findings.append(C.Finding(key, msg, new))
    if a.write_baseline:
        n = C.write_baseline(NAME, findings, [
            'check (b) check-expose: legacy findings (BUILD §7.3).',
            'Generated by: python3 scripts/check-expose.py --write-baseline'])
        print(f'{NAME}: wrote {n} baseline entries')
        return 0
    print(f'{NAME}: {n_proof} proof modules; {len(allow)} allow-list entries; '
          f'{len(kitfg_defs)} KitFG definition modules')
    return 1 if C.evaluate(NAME, findings, a.list_legacy) else 0


if __name__ == '__main__':
    sys.exit(main())
