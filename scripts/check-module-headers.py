#!/usr/bin/env python3
"""Check (a), BUILD §7.2 B1 and §7.3: module headers.

- Every library file (scripts/check_common.py: library_files) starts with
  the `module` command (the first token after blank lines and comments).
- The imports after `module` are `public import` only, with these
  exceptions: a plain `import` of a tactic module (a module name with a
  `Tactic` component, or Aesop, Plausible); `public meta import` only in a
  file under Tests/. `import all` never. A `meta import` without `public`,
  a `private import`, and a `meta import` outside Tests/ are findings.
- A script (scripts/*.lean, not in a library) stays a plain file: it does
  not start with `module`.

Baseline: scripts/baselines/check-module-headers.txt (legacy findings);
scope: scripts/new-libraries.txt. Exit 0: no failing finding; 1: a failing
finding. Run: python3 scripts/check-module-headers.py [--list-legacy]
[--write-baseline]."""
import argparse
import os
import re
import sys

sys.dont_write_bytecode = True
import check_common as C  # noqa: E402

NAME = 'check-module-headers'


def tactic_module(t):
    comps = t.split('.')
    return 'Tactic' in comps or comps[0] in ('Aesop', 'Plausible')


def main():
    a = C.standard_args(argparse.ArgumentParser(description=__doc__.split('\n')[0])).parse_args()
    scope = C.Scope()
    lib_files = C.library_files()
    findings = []
    for lf in lib_files:
        new = scope.is_new_file(lf)
        is_module, imps = C.header(lf)
        if not is_module:
            findings.append(C.Finding(f'not-module {lf.path}',
                                      f'{lf.path}: does not start with `module`', new))
            continue
        for (line, vis, meta, allm, t) in imps:
            where = f'{lf.path}:{line}'
            if allm:
                kind = 'import-all'
            elif meta:
                kind = None if (vis == 'public' and lf.is_test) else 'meta-import'
            elif vis == 'public':
                kind = None
            elif vis == '':
                kind = None if tactic_module(t) else 'plain-import'
            else:
                kind = 'other-import'
            if kind:
                text = ' '.join(x for x in (vis, 'meta' if meta else '', 'import',
                                            'all' if allm else '', t) if x)
                findings.append(C.Finding(f'{kind} {lf.path} {t}', f'{where}: {kind}: `{text}`', new))
    lib_paths = {lf.path for lf in lib_files}
    for f in sorted(os.listdir(C.SCRIPTS)):
        p = os.path.join('scripts', f)
        if f.lower().endswith('.lean') and p not in lib_paths:
            src = C.strip(open(os.path.join(C.ROOT, p), encoding='utf-8').read())
            if re.match(r'\s*module\b', src):
                findings.append(C.Finding(f'script-module {p}',
                                          f'{p}: a script starts with `module`'))
    if a.write_baseline:
        n = C.write_baseline(NAME, findings, [
            'check (a) check-module-headers: legacy findings (BUILD §7.3).',
            'Generated by: python3 scripts/check-module-headers.py --write-baseline'])
        print(f'{NAME}: wrote {n} baseline entries')
        return 0
    print(f'{NAME}: {len(lib_files)} library files')
    return 1 if C.evaluate(NAME, findings, a.list_legacy) else 0


if __name__ == '__main__':
    sys.exit(main())
