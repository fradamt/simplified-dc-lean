#!/usr/bin/env python3
"""Check (g), BUILD §7.2 B9 and §7.3: the longest import chain per library.

The graph: every library file and its imports of other library files (from
the source headers; the S4 method, a0-s4-build.md §1.1). A chain counts
modules. Per library:
- Global: the longest chain that starts at a module of the library (it may
  pass through other libraries);
- Local: the longest chain that stays in the library.

Baseline scripts/baselines/chain-depth.txt: `<Library> <Global>` per legacy
library. A legacy library whose Global depth is above its baseline fails (a
B9 regression: shorten the chain, or review and raise the baseline with
--write-baseline). A new library (scripts/new-libraries.txt) is reported
only: its limit is the G-F0a target (BUILD §7.6). A legacy library with no
baseline line fails.

Run: python3 scripts/chain-depth.py [--chain <Library>] [--write-baseline].
Exit 0: no regression; 1: a regression."""
import argparse
import sys

sys.dont_write_bytecode = True
import check_common as C  # noqa: E402

NAME = 'chain-depth'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--chain', action='append', default=[],
                    help='print the longest chain of this library in full')
    ap.add_argument('--write-baseline', action='store_true')
    a = ap.parse_args()
    scope = C.Scope()
    files = C.library_files()
    lib = {lf.module: lf.lib for lf in files}
    graph = {m: [t for t in ts if t in lib] for m, ts in C.import_graph(files).items()}
    sys.setrecursionlimit(20000)

    def longest(restrict):
        memo = {}

        def go(m, stack=()):
            if m in memo:
                return memo[m]
            if m in stack:
                sys.exit(f'import cycle through {m}')
            best = [m]
            for t in graph[m]:
                if restrict and lib[t] != lib[m]:
                    continue
                c = go(t, stack + (m,))
                if len(c) + 1 > len(best):
                    best = [m] + c
            memo[m] = best
            return best
        return go

    glob, loc = longest(False), longest(True)
    libs = [n for n, _ in C.libraries()]
    rows = []
    for L in libs:
        mods = [m for m in graph if lib[m] == L]
        if not mods:
            continue
        g = max((glob(m) for m in mods), key=len)
        l = max((loc(m) for m in mods), key=len)
        rows.append((L, len(mods), g, l))

    if a.write_baseline:
        with open(C.baseline_path(NAME), 'w', encoding='utf-8') as f:
            f.write('# check (g) chain-depth: <Library> <Global depth> of each legacy library (BUILD §7.3).\n')
            f.write('# Generated by: python3 scripts/chain-depth.py --write-baseline\n')
            for L, n, g, l in rows:
                if L not in scope.new_libs:
                    f.write(f'{L} {len(g)}\n')
        print(f'{NAME}: wrote the baseline')
        return 0

    base = {}
    for line in open(C.baseline_path(NAME), encoding='utf-8'):
        if line.strip() and not line.startswith('#'):
            k, v = line.split()
            base[k] = int(v)

    w = max(len(r[0]) for r in rows)
    top = f'┌{"─" * (w + 2)}┬─────────┬────────┬───────┬──────────┬{"─" * 12}┐'
    print(top)
    print(f'│ {"Library".ljust(w)} │ Modules │ Global │ Local │ Baseline │ {"Result".ljust(10)} │')
    print(top.replace('┌', '├').replace('┬', '┼').replace('┐', '┤'))
    fails = []
    for L, n, g, l in rows:
        new = L in scope.new_libs
        b = base.get(L)
        if new:
            res, bs = 'REPORT', '—'
        elif b is None:
            res, bs = 'FAIL', 'none'
            fails.append(f'{L}: no baseline line')
        elif len(g) > b:
            res, bs = 'FAIL', str(b)
            fails.append(f'{L}: Global {len(g)} > baseline {b}: {" → ".join(g)}')
        else:
            res, bs = ('PASS' if len(g) == b else 'PASS (<)'), str(b)
        print(f'│ {L.ljust(w)} │ {n:7d} │ {len(g):6d} │ {len(l):5d} │ {bs:>8} │ {res.ljust(10)} │')
    print(top.replace('┌', '└').replace('┬', '┴').replace('┐', '┘'))
    L, n, g, l = max(rows, key=lambda r: len(r[2]))
    print(f'longest chain: {len(g)} modules: {g[0]} → … → {g[-1]}')
    for want in a.chain:
        for L, n, g, l in rows:
            if L == want:
                print(f'{L} global chain ({len(g)}):')
                print('\n'.join('  ' + m for m in g))
    for f in fails:
        print('FAIL ' + f)
    print(f'{NAME}: {"FAIL" if fails else "PASS"}: {len(fails)} failing')
    return 1 if fails else 0


if __name__ == '__main__':
    sys.exit(main())
